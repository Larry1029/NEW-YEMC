CREATE TABLE IF NOT EXISTS application_change_requests (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  application_id BIGINT NOT NULL,
  request_type TEXT NOT NULL CHECK (request_type IN ('edit', 'delete')),
  request_data JSONB,
  status TEXT NOT NULL DEFAULT 'pending'
    CHECK (status IN ('pending', 'approved', 'rejected')),
  requested_by BIGINT REFERENCES auth_users(id) ON DELETE SET NULL,
  requester_name TEXT,
  requester_email TEXT NOT NULL,
  reviewed_by BIGINT REFERENCES auth_users(id) ON DELETE SET NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  reviewed_at TIMESTAMPTZ,
  CHECK (
    (request_type = 'edit' AND request_data IS NOT NULL)
    OR (request_type = 'delete' AND request_data IS NULL)
  )
);

CREATE INDEX IF NOT EXISTS application_change_requests_pending_idx
  ON application_change_requests (status, created_at DESC);
